#!/usr/bin/env python3
"""AI Risk Guardian agent — the off-chain model that drives the on-chain guardian.

Loop:
  1. Polls the Uniswap V2 pair reserves on Base Sepolia and derives the
     risk-token price series (stable per risk token).
  2. Computes features: fast/slow momentum, realized volatility, drawdown.
  3. Scores them with a logistic-regression model that estimates the
     probability of a near-term adverse move ("crash risk").
  4. Publishes its decision to SignalRegistry on Base Sepolia:
       - riskOff flag (immediate defensive exit),
       - a dynamic stop-loss rate (volatility-scaled distance below spot),
       - a take-profit rate,
       - the model score.
     The reactive contract on Lasna consumes these signals trustlessly.

Model training: the pair used here is a fresh testnet pair with no market
history, so the model is trained on synthetic price paths generated by a
two-regime simulator (calm regime: small positive drift, low volatility;
stressed regime: negative drift, high volatility, occasional jumps). Labels
mark whether the path loses more than 2% over the following 10 steps.
Training is deterministic (fixed seed) and uses only the Python standard
library. On a production pair the same pipeline would train on real history;
the feature/decision code would not change.

Usage:
  python3 agent.py once         # sample, decide, publish one signal
  python3 agent.py run          # continuous loop (default 15 min)
  python3 agent.py train-info   # print model weights + training accuracy

Config (env):
  BASE_RPC        Base Sepolia RPC URL (default https://sepolia.base.org)
  KEY_FILE        path to the agent private key file (default ~/.keys/reactive-omni.key)
  DEPLOYMENT_JSON path to deployment.json written by the deploy script
"""

import json
import math
import os
import random
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ethlite
from ethlite import Rpc, abi_bool, abi_uint, encode_call, privkey_to_address, sign_legacy_tx

BASE_RPC = os.environ.get("BASE_RPC", "https://sepolia.base.org")
KEY_FILE = os.environ.get("KEY_FILE", os.path.expanduser("~/.keys/reactive-omni.key"))
DEPLOYMENT_JSON = os.environ.get(
    "DEPLOYMENT_JSON",
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "deployment.json"),
)
CHAIN_ID = 84532  # Base Sepolia

GET_RESERVES = "0x0902f1ac"  # getReserves()

# ------------------------------------------------------------------ model

FEATURE_NAMES = ["bias", "ret_fast", "ret_slow", "vol", "drawdown"]


def compute_features(rates):
    """Features from a list of recent rates (oldest -> newest)."""
    n = len(rates)
    cur = rates[-1]
    logrets = [math.log(rates[i] / rates[i - 1]) for i in range(1, n) if rates[i - 1] > 0]
    ret_fast = math.log(cur / rates[-6]) if n >= 6 and rates[-6] > 0 else (logrets[-1] if logrets else 0.0)
    ret_slow = math.log(cur / rates[-21]) if n >= 21 and rates[-21] > 0 else (sum(logrets) if logrets else 0.0)
    window = logrets[-20:]
    if len(window) >= 2:
        mean = sum(window) / len(window)
        vol = math.sqrt(sum((x - mean) ** 2 for x in window) / (len(window) - 1))
    else:
        vol = 0.0
    peak = max(rates[-50:]) if rates else cur
    drawdown = (cur / peak - 1.0) if peak > 0 else 0.0
    return [1.0, ret_fast, ret_slow, vol, drawdown]


def simulate_training_data(seed=42, paths=260, steps=90):
    """Two-regime price-path simulator producing (features, label) samples."""
    rng = random.Random(seed)
    samples = []
    for _ in range(paths):
        price = 1.0
        rates = [price]
        regime = 0  # 0 calm, 1 stressed
        for _ in range(steps):
            if rng.random() < 0.03:
                regime = 1 - regime
            if regime == 0:
                drift, vol = 0.0002, 0.0015
            else:
                drift, vol = -0.0025, 0.008
            shock = rng.gauss(drift, vol)
            if regime == 1 and rng.random() < 0.05:
                shock -= rng.uniform(0.01, 0.04)  # jump down
            price *= math.exp(shock)
            rates.append(price)
        for t in range(25, steps - 10):
            feats = compute_features(rates[: t + 1])
            future = rates[t + 10] / rates[t] - 1.0
            label = 1 if future < -0.02 else 0
            samples.append((feats, label))
    return samples


def train_logistic_regression(samples, epochs=300, lr=0.5, l2=1e-4):
    """Plain gradient descent; features standardized with train statistics."""
    dim = len(samples[0][0])
    means = [0.0] * dim
    stds = [1.0] * dim
    for j in range(1, dim):  # skip bias
        col = [s[0][j] for s in samples]
        means[j] = sum(col) / len(col)
        var = sum((x - means[j]) ** 2 for x in col) / len(col)
        stds[j] = math.sqrt(var) if var > 1e-12 else 1.0

    def norm(feats):
        return [feats[0]] + [(feats[j] - means[j]) / stds[j] for j in range(1, dim)]

    w = [0.0] * dim
    for _ in range(epochs):
        grad = [0.0] * dim
        for feats, label in samples:
            x = norm(feats)
            z = sum(wj * xj for wj, xj in zip(w, x))
            p = 1.0 / (1.0 + math.exp(-z)) if -35 < z < 35 else (1.0 if z >= 35 else 0.0)
            err = p - label
            for j in range(dim):
                grad[j] += err * x[j] + l2 * w[j]
        for j in range(dim):
            w[j] -= lr * grad[j] / len(samples)

    correct = 0
    for feats, label in samples:
        if (predict_proba_raw(w, means, stds, feats) >= 0.5) == bool(label):
            correct += 1
    return {"weights": w, "means": means, "stds": stds, "train_accuracy": correct / len(samples)}


def predict_proba(model, feats):
    return predict_proba_raw(model["weights"], model["means"], model["stds"], feats)


def predict_proba_raw(w, means, stds, feats):
    x = [feats[0]] + [(feats[j] - means[j]) / stds[j] for j in range(1, len(feats))]
    z = sum(wj * xj for wj, xj in zip(w, x))
    if z >= 35:
        return 1.0
    if z <= -35:
        return 0.0
    return 1.0 / (1.0 + math.exp(-z))


# ------------------------------------------------------------------ chain io

class Guardian:
    def __init__(self):
        with open(KEY_FILE) as f:
            self.privkey = bytes.fromhex(f.read().strip().removeprefix("0x"))
        self.address = privkey_to_address(self.privkey)
        with open(DEPLOYMENT_JSON) as f:
            dep = json.load(f)
        self.pair = dep["pair"]
        self.registry = dep["signalRegistry"]
        self.risk_is_token0 = bool(dep["riskIsToken0"])
        self.rpc = Rpc(BASE_RPC)
        self.rates = []

    def poll_rate(self):
        out = self.rpc.eth_call(self.pair, GET_RESERVES)
        raw = bytes.fromhex(out[2:])
        reserve0 = int.from_bytes(raw[0:32], "big")
        reserve1 = int.from_bytes(raw[32:64], "big")
        rate = (reserve1 / reserve0) if self.risk_is_token0 else (reserve0 / reserve1)
        self.rates.append(rate)
        if len(self.rates) > 300:
            self.rates.pop(0)
        return rate

    def publish_signal(self, risk_off, stop_rate, take_profit_rate, score):
        stop_i = int(stop_rate * 10**18)
        tp_i = int(take_profit_rate * 10**18)
        score_i = int(score * 10000)
        data = encode_call(
            "updateSignal(bool,uint256,uint256,int256)",
            abi_bool(risk_off),
            abi_uint(stop_i),
            abi_uint(tp_i),
            abi_uint(score_i),
        )
        nonce = self.rpc.get_transaction_count(self.address)
        gas_price = self.rpc.gas_price() * 2 + 10**9
        raw = sign_legacy_tx(
            self.privkey,
            nonce=nonce,
            gas_price=gas_price,
            gas_limit=200_000,
            to=self.registry,
            value=0,
            data=bytes.fromhex(data[2:]),
            chain_id=CHAIN_ID,
        )
        tx_hash = self.rpc.send_raw(raw)
        receipt = self.rpc.wait_receipt(tx_hash)
        if receipt.get("status") != "0x1":
            raise RuntimeError(f"updateSignal reverted: {tx_hash}")
        return tx_hash


# ------------------------------------------------------------------ decision

def decide(model, rates):
    feats = compute_features(rates)
    score = predict_proba(model, feats)
    rate = rates[-1]
    vol = feats[3]
    # Volatility-scaled stop distance: at least 5%, at most 25% below spot.
    vol_window = vol * math.sqrt(20)
    stop_distance = min(0.25, max(0.05, 3.0 * vol_window))
    stop_rate = rate * (1.0 - stop_distance)
    take_profit_rate = rate * 1.15
    risk_off = score >= 0.65 or feats[4] <= -0.12
    return {
        "rate": rate,
        "score": score,
        "features": dict(zip(FEATURE_NAMES, feats)),
        "risk_off": risk_off,
        "stop_rate": stop_rate,
        "take_profit_rate": take_profit_rate,
        "stop_distance": stop_distance,
    }


def log(msg):
    line = f"[{time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}] {msg}"
    print(line, flush=True)
    log_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "agent.log")
    with open(log_path, "a") as f:
        f.write(line + "\n")


# ------------------------------------------------------------------ modes

def collect_samples(guardian, count, interval):
    for _ in range(count):
        rate = guardian.poll_rate()
        log(f"sample rate={rate:.6f} reserves_samples={len(guardian.rates)}")
        time.sleep(interval)


def run_once(model):
    g = Guardian()
    log(f"agent address {g.address}; pair {g.pair}; registry {g.registry}")
    collect_samples(g, count=12, interval=2.0)
    d = decide(model, g.rates)
    log(f"decision {json.dumps(d)}")
    tx = g.publish_signal(d["risk_off"], d["stop_rate"], d["take_profit_rate"], d["score"])
    log(f"signal published tx={tx}")
    print(json.dumps({"tx": tx, "decision": d}))
    return tx


def run_loop(model, duration_s=900, interval=2.0):
    g = Guardian()
    log(f"agent address {g.address}; pair {g.pair}; registry {g.registry}")
    started = time.time()
    last_published = None
    last_publish_at = 0.0
    risk_off_published = False
    while time.time() - started < duration_s:
        try:
            g.poll_rate()
        except Exception as e:  # keep the loop alive through RPC hiccups
            log(f"poll error: {e}")
            time.sleep(interval)
            continue
        if len(g.rates) < 12:
            time.sleep(interval)
            continue
        d = decide(model, g.rates)
        now = time.time()
        need = (
            not risk_off_published
            and (
                last_published is None
                or d["risk_off"] != last_published["risk_off"]
                or abs(d["stop_rate"] - last_published["stop_rate"]) / last_published["stop_rate"] > 0.02
                or now - last_publish_at > 120
            )
        )
        if need:
            try:
                tx = g.publish_signal(d["risk_off"], d["stop_rate"], d["take_profit_rate"], d["score"])
                log(f"signal published tx={tx} decision={json.dumps(d)}")
                last_published = d
                last_publish_at = now
                if d["risk_off"]:
                    # Once the model declares risk-off, the guardian has its
                    # marching orders. The agent stops publishing so it cannot
                    # re-arm the guardian mid-incident; an operator resets it.
                    risk_off_published = True
                    log("risk-off published; agent will not publish further signals this run")
            except Exception as e:
                log(f"publish error: {e}")
        time.sleep(interval)
    log("run finished")


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "once"
    samples = simulate_training_data()
    model = train_logistic_regression(samples)
    if mode == "train-info":
        print(json.dumps({"samples": len(samples), **model}, indent=2))
    elif mode == "once":
        run_once(model)
    elif mode == "run":
        duration = int(sys.argv[2]) if len(sys.argv) > 2 else 900
        run_loop(model, duration_s=duration)
    else:
        print(__doc__)
        sys.exit(2)


if __name__ == "__main__":
    main()
